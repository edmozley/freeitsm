<?php
/**
 * Debug Tool D021 - The notification bell against the ticket's own history.
 *
 * Answers one question for one ticket: "the bell says 'Handed to your team by X' -
 * did X really do that, or did something else?" (GH #365).
 *
 * The bell does not store its sentence. Each row keeps an event type and a COPY of
 * a name (notifications.actor_name), and the browser builds "Handed to your team
 * by {actor}" from them. Before 5.8.0 that name was whoever was signed in for the
 * web request, even when the change was made by a workflow running inside it - so
 * an automatic change could be credited to a person who never touched the ticket.
 *
 * The ticket's audit trail is the record of who really did it: a person, or
 * "System" (analyst_id NULL) for a workflow. This tool lists both and pairs them:
 *
 *   bell event                 compared with
 *   ticket.team_assigned       the audit line for Team
 *   ticket.assigned/reassigned the audit line for Owner
 *   ticket.status_changed      the audit line for Status
 *   ticket.priority_changed    the audit line for Priority
 *   ticket.created             the audit line for Ticket Created
 *   ticket.note_added          the note itself (ticket_notes.analyst_id; NULL = a workflow)
 *   ticket.reply_received      the inbound email (who sent it)
 *
 * ⚠️ IT PAIRS BY KIND AND TIME, NOT BY A LINK. A bell row written before 5.8.0
 * holds no id of the change that caused it, and on screen the audit line is
 * written by a separate request from the change. So each bell row is paired with
 * the nearest history line of its kind within D021_WINDOW seconds, and the report
 * says how far apart they were. Rows from 5.8.0 on also carry actor_kind and
 * source, which the report shows and trusts first.
 *
 * ⚠️ A GROUPED ROW ("3 updates") keeps only its latest time, so only that one
 * change can be checked; the report says so rather than passing it.
 *
 * Also listed: workflow runs on this ticket (workflow_executions) near each bell
 * row - the quickest way to see that a workflow, not a person, made the change.
 *
 * Read-only. Administrators only. Output: plain text, === sections ===.
 */

@session_start();

$DIAG_ID   = 'D021';
$DIAG_NAME = 'Notification bell against the ticket history';
const D021_WINDOW = 120;          // seconds either side to look for the matching history line

$sections = [];
/**
 * Adds one titled section to the report.
 *
 * @param array $sections  the report so far, appended to by reference
 * @param string $title  the heading, printed between === marks
 * @param string|array $body  the section text, or its lines
 */
function d021_section(array &$sections, string $title, $body): void {
    if (is_array($body)) $body = implode("\n", $body);
    $sections[] = "=== {$title} ===\n" . rtrim($body, "\n");
}
/** Prints the report and stops. */
function d021_emit(array $sections): void {
    if (!headers_sent()) {
        header('Content-Type: text/plain; charset=utf-8');
        header('Cache-Control: no-store');
    }
    echo implode("\n\n", $sections) . "\n";
    exit;
}

// ---- 1. Header, input, admin gate -------------------------------------------

$ref = trim((string)($_GET['ref'] ?? $_POST['ref'] ?? ''));
d021_section($sections, 'REPORT HEADER', [
    "Diagnostic     : {$DIAG_ID} - {$DIAG_NAME}",
    'Generated      : ' . gmdate('Y-m-d H:i:s') . ' UTC',
    'Generated by   : analyst_id=' . ($_SESSION['analyst_id'] ?? '(not logged in)'),
    'Ticket ref in  : ' . ($ref === '' ? '(none supplied)' : $ref),
    'Side effects   : none - read-only.',
    'Times          : UTC, as stored.',
]);
if (!isset($_SESSION['analyst_id'])) {
    d021_section($sections, 'AUTH', 'FAIL: not logged in. Sign in to FreeITSM in the same browser, then run it again.');
    d021_emit($sections);
}
if ($ref === '') {
    d021_section($sections, 'INPUT', 'FAIL: no ticket reference. Type the ticket number shown in the bell (e.g. TICKET-000107) and click Run.');
    d021_emit($sections);
}
require_once __DIR__ . '/../../../config.php';
require_once __DIR__ . '/../../../includes/functions.php';
try {
    $conn = connectToDatabase();
    $isAdmin = analystIsAdmin($conn, (int)$_SESSION['analyst_id']);
} catch (Throwable $e) {
    $isAdmin = false;
}
if (!$isAdmin) {   // Debug tools are administrators-only (issue #34). Fail closed.
    http_response_code(403);
    header('Content-Type: text/plain; charset=utf-8');
    echo "Administrator access required.\n";
    exit;
}

// ---- 2. The ticket ------------------------------------------------------------

$st = $conn->prepare('SELECT id, ticket_number, subject, assigned_team_id, assigned_analyst_id, tenant_id FROM tickets WHERE ticket_number = ?');
$st->execute([$ref]);
$t = $st->fetch(PDO::FETCH_ASSOC);
if (!$t && ctype_digit($ref)) {
    $st = $conn->prepare('SELECT id, ticket_number, subject, assigned_team_id, assigned_analyst_id, tenant_id FROM tickets WHERE id = ?');
    $st->execute([(int)$ref]);
    $t = $st->fetch(PDO::FETCH_ASSOC);
}
if (!$t) {
    d021_section($sections, 'TICKET', "FAIL: no ticket with the number (or id) '{$ref}'.");
    d021_emit($sections);
}
$tid = (int)$t['id'];
$name = function (?int $analystId) use ($conn): string {
    if (!$analystId) return '(nobody)';
    static $cache = [];
    if (!isset($cache[$analystId])) {
        $s = $conn->prepare('SELECT full_name FROM analysts WHERE id = ?');
        $s->execute([$analystId]);
        $cache[$analystId] = ($n = $s->fetchColumn()) !== false ? (string)$n : "(former analyst #{$analystId})";
    }
    return $cache[$analystId];
};
$teamName = function ($id) use ($conn): string {
    if (!$id) return '(none)';
    $s = $conn->prepare('SELECT name FROM teams WHERE id = ?'); $s->execute([(int)$id]);
    return ($n = $s->fetchColumn()) !== false ? (string)$n : "(team #{$id})";
};
d021_section($sections, 'TICKET', [
    'Number   : ' . $t['ticket_number'] . "   (id {$tid})",
    'Subject  : ' . mb_substr((string)$t['subject'], 0, 120),
    'Team now : ' . $teamName($t['assigned_team_id']),
    'Owner now: ' . $name($t['assigned_analyst_id'] !== null ? (int)$t['assigned_analyst_id'] : null),
]);

// ---- 3. What the bell recorded --------------------------------------------------

$cols = $conn->query("SHOW COLUMNS FROM notifications")->fetchAll(PDO::FETCH_COLUMN);
$extra = array_values(array_intersect(['actor_kind', 'actor_analyst_id', 'source', 'workflow_id', 'api_key_id'], $cols));   // 5.8.0+
$bell = $conn->prepare('SELECT n.*, a.full_name AS recipient FROM notifications n LEFT JOIN analysts a ON a.id = n.analyst_id
                         WHERE n.entity_type = \'ticket\' AND n.entity_id = ? ORDER BY n.created_datetime, n.id');
$bell->execute([$tid]);
$rows = $bell->fetchAll(PDO::FETCH_ASSOC);

// The English wording, built exactly as the bell builds it in the browser.
$en = @include __DIR__ . '/../../../lang/en/common.php';
$words = function (array $r) use ($en): string {
    // 'ticket.team_assigned' lives at notifications.event.ticket.team_assigned.
    $tpl = $en['notifications']['event'] ?? null;
    foreach (explode('.', (string)$r['event_type']) as $part) $tpl = is_array($tpl) ? ($tpl[$part] ?? null) : null;
    if (!is_string($tpl)) $tpl = null;
    $kind = $r['actor_kind'] ?? null;
    if ($kind === 'workflow') $actor = str_replace('{name}', (string)$r['actor_name'], $en['notifications']['actor_workflow'] ?? 'the workflow "{name}"');
    elseif ($kind === 'system') $actor = ($r['source'] ?? '') === 'mail_import' ? ($en['notifications']['actor_email'] ?? 'email') : ($en['notifications']['actor_system'] ?? 'FreeITSM');
    else $actor = $r['actor_name'] !== null && $r['actor_name'] !== '' ? $r['actor_name'] : ($en['notifications']['someone'] ?? 'Someone');
    return $tpl ? str_replace('{actor}', $actor, preg_replace('/\{to\}/', '...', $tpl)) : "({$r['event_type']}) {$actor}";
};

// One change reaches several people (a team), so rows of the same kind written
// within a few seconds of each other are one change with several recipients.
$changes = [];
foreach ($rows as $r) {
    $ts = strtotime($r['created_datetime'] . ' UTC');
    $last = end($changes);
    if ($last && $last['event_type'] === $r['event_type'] && abs($ts - $last['ts']) <= 5 && $last['actor_name'] === $r['actor_name']) {
        $changes[key($changes)]['recipients'][] = $r['recipient'] ?? ('#' . $r['analyst_id']);
        $changes[key($changes)]['grouped'] = $changes[key($changes)]['grouped'] || (int)$r['event_count'] > 1;
        continue;
    }
    $changes[] = ['event_type' => $r['event_type'], 'ts' => $ts, 'time' => $r['created_datetime'], 'updated' => $r['updated_datetime'],
        'actor_name' => $r['actor_name'], 'words' => $words($r), 'recipients' => [$r['recipient'] ?? ('#' . $r['analyst_id'])],
        'grouped' => (int)$r['event_count'] > 1, 'extra' => array_intersect_key($r, array_flip($extra))];
}
$b = [];
if (!$rows) $b[] = 'No bell rows for this ticket. (Read rows are kept, so this means none were ever written - or they were cleared.)';
foreach ($changes as $i => $c) {
    $b[] = sprintf('#%d  %s  %s', $i + 1, $c['time'], $c['event_type']);
    $b[] = '     Says      : "' . $c['words'] . '"';
    $b[] = '     Name kept : ' . ($c['actor_name'] ?? '(none - a system event)');
    foreach ($c['extra'] as $k => $v) $b[] = sprintf('     %-17s: %s', $k, $v === null ? '-' : $v);
    if (!$extra) $b[] = '     Recorded  : name only (a row written before 5.8.0 keeps no actor id or kind)';
    $b[] = '     Sent to   : ' . implode(', ', array_unique($c['recipients']));
    if ($c['grouped']) $b[] = '     GROUPED   : several events on this ticket arrived before it was read, and the bell merged them into this one row - it keeps only the LATEST event\'s kind, name and time (' . $c['updated'] . '); the earlier ones were overwritten and cannot be checked from the bell';
}
d021_section($sections, 'WHAT THE BELL RECORDED (' . count($rows) . ' rows, ' . count($changes) . ' changes)', $b);

// ---- 4. What the ticket's history recorded ---------------------------------------

$au = $conn->prepare('SELECT id, analyst_id, field_name, old_value, new_value, created_datetime FROM ticket_audit WHERE ticket_id = ? ORDER BY created_datetime, id');
$au->execute([$tid]);
$audit = $au->fetchAll(PDO::FETCH_ASSOC);
$who = fn(array $a): string => $a['analyst_id'] === null ? 'System (automatic - a workflow or the system)' : $name((int)$a['analyst_id']);
$h = [];
foreach ($audit as $a) {
    $h[] = sprintf('%s  %-16s %s -> %s   by %s', $a['created_datetime'], $a['field_name'],
        mb_substr((string)($a['old_value'] ?? '-'), 0, 30), mb_substr((string)($a['new_value'] ?? '-'), 0, 30), $who($a));
}
d021_section($sections, 'WHAT THE TICKET HISTORY RECORDED (' . count($audit) . ' lines)', $h ?: ['No history lines.']);

// Workflow runs on this ticket, for the evidence column.
$runs = [];
try {
    $wr = $conn->prepare("SELECT id, workflow_id, workflow_name, trigger_event, status, is_dry_run, started_datetime FROM workflow_executions
                           WHERE JSON_UNQUOTE(JSON_EXTRACT(trigger_payload, '$.ticket.id')) = ? ORDER BY started_datetime");
    $wr->execute([(string)$tid]);
    $runs = $wr->fetchAll(PDO::FETCH_ASSOC);
} catch (Throwable $e) {
    $runs = null;   // no table, or a payload MySQL cannot read as JSON
}
$w = [];
if ($runs === null) $w[] = '(could not read workflow runs on this install)';
elseif (!$runs) $w[] = 'No workflow ran on this ticket.';
else foreach ($runs as $r) $w[] = sprintf('%s  "%s" (workflow #%d) on %s - %s%s', $r['started_datetime'], $r['workflow_name'], $r['workflow_id'], $r['trigger_event'], $r['status'], $r['is_dry_run'] ? ' (dry run)' : '');
d021_section($sections, 'WORKFLOWS THAT RAN ON THIS TICKET', $w);

// ---- 5. Pair each bell change with its history -----------------------------------------

// The SAME matching the bell's (i) panel uses (includes/notification_explain.php), so the
// tool and the panel can never give different answers about one row.
require_once __DIR__ . '/../../../includes/notification_explain.php';
$usedAudit = [];
$verdicts = ['MATCH' => 0, 'MISMATCH' => 0, 'AUTOMATIC CREDITED TO A PERSON' => 0, 'NOT FOUND' => 0, 'NOT CHECKED' => 0];
$p = [];
foreach ($changes as $i => $c) {
    $ts = $c['grouped'] ? strtotime($c['updated'] . ' UTC') : $c['ts'];
    $label = sprintf('#%d %s (%s)', $i + 1, $c['event_type'], $c['grouped'] ? $c['updated'] . ', the latest of a grouped row' : $c['time']);
    $evidence = null; $actual = null; $isSystem = false; $gap = null;

    $m = notificationHistoryMatch($conn, $tid, (string)$c['event_type'], $ts, $usedAudit);
    if ($m !== null && $m['kind'] === 'none') {
        $verdicts['NOT CHECKED']++;
        $p[] = "{$label}\n     NOT CHECKED - nothing in the ticket history records this kind of event.";
        continue;
    }
    if ($m !== null) {
        if ($m['kind'] === 'audit') $usedAudit[$m['id']] = true;
        $isSystem = $m['by_kind'] === 'system';
        $actual = $m['by_kind'] === 'system' ? ($m['kind'] === 'note' ? 'System (a note added by a workflow)' : 'System (automatic - a workflow or the system)')
                : ($m['by_kind'] === 'former' ? '(former analyst)' : (string)$m['by_name']);
        $gap = $m['gap'];
        $evidence = $m['kind'] === 'audit' ? "history line {$m['time']} {$m['field']} -> " . ($m['new'] ?? '-')
                  : ($m['kind'] === 'note' ? "note written {$m['time']}" : "email received {$m['time']} (a reply is announced when it is fetched, so a gap is normal)");
    }

    if ($evidence === null) {
        $verdicts['NOT FOUND']++;
        $p[] = "{$label}\n     NOT FOUND - no matching history within " . D021_WINDOW . "s. The change may have been made by something that writes no history line, or the history was written much later.";
        continue;
    }
    $bellName = (string)($c['actor_name'] ?? '');
    $bellKind = $c['extra']['actor_kind'] ?? null;   // recorded from 5.8.0; null on older rows
    $runsNear = [];
    foreach ((array)$runs as $r) if (abs(strtotime($r['started_datetime'] . ' UTC') - $ts) <= D021_WINDOW) $runsNear[] = '"' . $r['workflow_name'] . '" at ' . $r['started_datetime'];
    if ($isSystem && in_array($bellKind, ['workflow', 'system'], true)) {
        $v = 'MATCH';
        $why = 'the bell recorded an automatic change (' . $bellKind . ($bellName !== '' ? ': ' . $bellName : '') . ') and the history agrees';
    } elseif ($isSystem && $bellName !== '') {
        $v = 'AUTOMATIC CREDITED TO A PERSON';
        $why = "the history says an automatic change made it, but the bell names {$bellName} - the person whose session it ran in, not the person who did it (GH #365)";
    } elseif (!$isSystem && $actual !== null && $bellName !== '' && mb_strtolower($bellName) !== mb_strtolower(preg_replace('/\s*<.*$/', '', $actual))) {
        $v = 'MISMATCH';
        $why = "the bell names {$bellName}, the history names {$actual}";
    } else {
        $v = 'MATCH';
        $why = 'the bell and the history agree';
    }
    $verdicts[$v]++;
    $p[] = "{$label}\n     Bell says    : " . ($bellName !== '' ? $bellName : '(no name)')
         . "\n     History says : {$actual}\n     Evidence     : {$evidence}" . ($gap !== null ? " ({$gap}s apart)" : '')
         . ($runsNear ? "\n     Workflow runs near then: " . implode('; ', $runsNear) : '')
         . "\n     VERDICT      : {$v} - {$why}";
}
d021_section($sections, 'BELL AGAINST HISTORY', $p ?: ['Nothing to compare.']);

// ---- 6. Verdict ------------------------------------------------------------------

$sum = [];
foreach ($verdicts as $k => $n) if ($n) $sum[] = sprintf('%-32s %d', $k, $n);
if ($verdicts['AUTOMATIC CREDITED TO A PERSON']) {
    $sum[] = '';
    $sum[] = 'An automatic change (usually a workflow) was announced in the bell under a person\'s name. Before 5.8.0 the bell named whoever was';
    $sum[] = 'signed in for the request the change ran inside - often just someone whose inbox was open. The history line is the truth.';
}
if ($verdicts['MISMATCH']) {
    $sum[] = '';
    $sum[] = 'The bell and the history name different people. Paste this report into a bug report as it is.';
}
if (!$extra) {
    $sum[] = '';
    $sum[] = 'This install\'s bell rows keep a name only. From 5.8.0 they also record what made the change (a person, a workflow, the system) and its id.';
}
d021_section($sections, 'SUMMARY', $sum ?: ['No bell rows to check.']);
d021_emit($sections);
