 * Feature Bingo cards - Workflows: having workflows, the trigger families, the
 * action types, webhook formats, scheduled triggers and the module's settings.
 * See includes/feature_bingo.php for the format.
 *
 * workflows.trigger_event is one event name; workflows.actions is JSON written by
 * json_encode() (api/workflow/save.php, create_from_template.php, api/v1), so an
 * action appears as "type":"send_email" with no spaces. Only ACTIVE workflows
 * that the demo importer did not create count.
 */

$live = 'is_active = 1 AND is_demo = 0';
$trigger = function (string $where) use ($live): array {
    return ['rows', 'workflows', "$live AND ($where)"];
};
$action = function (string $type) use ($live): array {
    return ['rows', 'workflows', "$live AND actions LIKE '%\"type\":\"$type\"%'"];
};
$preset = function (string $key) use ($live): array {
    return ['rows', 'workflows', "$live AND actions LIKE '%\"type\":\"send_webhook\"%' AND actions LIKE '%\"preset\":\"$key\"%'"];
};

